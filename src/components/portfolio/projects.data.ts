export type ProjectKind = "web" | "mobile";

export interface ProjectScreenshot {
  src: string;
  alt: string;
}

export interface ProjectLinkSet {
  appStore?: string;
  googlePlay?: string;
}

interface BaseProject {
  title: string;
  description: string;
  kind: ProjectKind;
  featured?: boolean;
  category?: "Desktop";
  showcase?: {
    identity: string;
    composition?: "notch" | "mobile" | "editorial" | "invoice" | "workflow" | "dashboard" | "stack" | "campaign" | "calculator" | "gallery";
    tone: string;
    art: string;
    icon?: string;
    cover?: string;
    edition: string;
    headline: string;
    footer: string;
    primary?: number;
    secondary?: number;
    detail?: string;
  };
  caseStudy?: {
    challenge: string;
    approach: string;
    previewNote: string;
  };
  /** Problem space, derived from the description (Fintech, Payroll, …). */
  domain: string;
  /** Two–three capabilities lifted verbatim-ish from the description. */
  highlights: string[];
}

export interface WebProject extends BaseProject {
  kind: "web";
  images: ProjectScreenshot[];
  liveUrl?: string;
  repoUrl?: string;
}

export interface MobileProject extends BaseProject {
  kind: "mobile";
  platforms: Array<"iOS" | "Android">;
  screenshots: ProjectScreenshot[];
  storeLinks: ProjectLinkSet;
  downloadUrl?: string;
  caseStudyUrl?: string;
}

export type PortfolioProject = WebProject | MobileProject;

export const getProjectImages = (project: PortfolioProject) =>
  project.kind === "mobile" ? project.screenshots : project.images;
export const getProjectCategory = (project: PortfolioProject) =>
  project.category || (project.kind === "mobile" ? "Mobile" : "Web");
export const getProjectPlatform = (project: PortfolioProject) =>
  project.category === "Desktop"
    ? "macOS application"
    : project.kind === "mobile"
      ? project.platforms.join(" & ")
      : "Web application";

